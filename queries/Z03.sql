-- ============================================================
-- З-3. Агрегация посевных площадей
--      по муниципальным образованиям
-- ============================================================
-- Назначение:
-- определение количества пространственных объектов и
-- суммарной площади посевов по муниципальным образованиям.
--
-- Измерение:
--   муниципальное образование.
--
-- Показатели:
--   количество объектов;
--   площадь, га.
--
-- Для моделей I и II территориальная принадлежность
-- определяется непосредственно при выполнении запроса.
--
-- Для моделей III и IV результат пространственного
-- сопоставления формируется заранее на этапе предварительной
-- обработки данных.
--
-- Правило территориального отнесения:
--
--   1. для объекта определяются все пересекающиеся
--      муниципальные образования;
--   2. рассчитывается доля площади каждого пересечения;
--   3. выбирается максимальная доля;
--   4. при overlap_ratio > 0.8 объект относится
--      к соответствующему муниципальному образованию;
--   5. иначе используется категория «Не определено».
--
-- PARTITION BY season, id необходим, поскольку значения id
-- могут повторяться в разных сезонах.
-- ============================================================


-- ============================================================
-- MODEL I
-- Базовая реляционная модель
-- ============================================================

WITH candidates AS
(
    SELECT
        f.id,
        f.season,

        ST_Area(
            ST_Transform(f.geom, 3857)
        ) / 10000.0 AS area_ha,

        m."m.name" AS municipality,

        ST_Area(
            ST_Transform(
                ST_Intersection(f.geom, m.geom),
                3857
            )
        )
        /
        NULLIF(
            ST_Area(
                ST_Transform(f.geom, 3857)
            ),
            0
        ) AS overlap_ratio

    FROM public.v1_sowing_relational AS f

    JOIN public.municipalities AS m
      ON ST_Intersects(f.geom, m.geom)

    WHERE f.geom IS NOT NULL
      AND f.crop IS NOT NULL
),

best_match AS
(
    SELECT
        *,

        ROW_NUMBER() OVER
        (
            PARTITION BY season, id
            ORDER BY overlap_ratio DESC
        ) AS rn

    FROM candidates
),

assigned AS
(
    SELECT
        area_ha,

        CASE
            WHEN overlap_ratio > 0.8
                THEN municipality
            ELSE 'Не определено'
        END AS municipality

    FROM best_match

    WHERE rn = 1
)

SELECT
    municipality,
    COUNT(*) AS field_count,
    SUM(area_ha) AS area_ha

FROM assigned

GROUP BY municipality;


-- ============================================================
-- MODEL II
-- Реляционная модель с индексированием
-- ============================================================

WITH candidates AS
(
    SELECT
        f.id,
        f.season,

        ST_Area(
            ST_Transform(f.geom, 3857)
        ) / 10000.0 AS area_ha,

        m."m.name" AS municipality,

        ST_Area(
            ST_Transform(
                ST_Intersection(f.geom, m.geom),
                3857
            )
        )
        /
        NULLIF(
            ST_Area(
                ST_Transform(f.geom, 3857)
            ),
            0
        ) AS overlap_ratio

    FROM public.v2_sowing_indexed AS f

    JOIN public.municipalities AS m
      ON ST_Intersects(f.geom, m.geom)

    WHERE f.geom IS NOT NULL
      AND f.crop IS NOT NULL
),

best_match AS
(
    SELECT
        *,

        ROW_NUMBER() OVER
        (
            PARTITION BY season, id
            ORDER BY overlap_ratio DESC
        ) AS rn

    FROM candidates
),

assigned AS
(
    SELECT
        area_ha,

        CASE
            WHEN overlap_ratio > 0.8
                THEN municipality
            ELSE 'Не определено'
        END AS municipality

    FROM best_match

    WHERE rn = 1
)

SELECT
    municipality,
    COUNT(*) AS field_count,
    SUM(area_ha) AS area_ha

FROM assigned

GROUP BY municipality;


-- ============================================================
-- MODEL III
-- Материализованные представления
-- ============================================================

SELECT
    municipality,
    SUM(field_count) AS field_count,
    SUM(area_ha) AS area_ha

FROM public.mv_municipality_crop_season

GROUP BY municipality;


-- ============================================================
-- MODEL IV
-- Многомерная модель типа «звезда»
-- ============================================================

SELECT
    dm.municipality_name AS municipality,
    SUM(f.field_count) AS field_count,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_municipality AS dm
  ON dm.municipality_id = f.municipality_id

GROUP BY dm.municipality_name;


-- ============================================================
-- Проверка семантической эквивалентности
-- ============================================================
--
-- Перед измерением производительности результаты четырех
-- реализаций З-3 были сопоставлены по каждому муниципальному
-- образованию.
--
-- Для всех моделей совпадало количество исходных объектов.
-- Различия значений площади ограничивались погрешностью
-- вычислений double precision.
--
-- Общее количество объектов после исключения записей
-- с отсутствующими geom или crop:
--
--     324 314
--
-- Распределение объектов категории «Не определено»:
--
--     2024: 18
--     2025: 31
--     2026: 29
--
--     всего: 78
--
-- Таким образом, различия времени выполнения З-3
-- сравниваются при одинаковой логике территориального
-- отнесения объектов.
-- ============================================================


-- ============================================================
-- Особенность интерпретации производительности
-- ============================================================
--
-- Для моделей I и II пространственные операции
--
--     ST_Intersects
--     ST_Intersection
--     ST_Area
--     ST_Transform
--
-- выполняются непосредственно в ходе З-3.
--
-- Для моделей III и IV территориальная принадлежность
-- объектов уже определена на этапе предварительной обработки.
--
-- Поэтому время З-3 для III и IV характеризует скорость
-- выполнения аналитического запроса к подготовленной
-- структуре и не включает стоимость ее первоначального
-- формирования.
--
-- Затраты на предварительную обработку моделей III и IV
-- измеряются и приводятся отдельно.
-- ============================================================


-- ============================================================
-- Измерение производительности
-- ============================================================
--
-- Протокол измерения:
--
--   cold:
--       5 измерений;
--       перед каждым запуском очищался PostgreSQL
--       shared buffer cache;
--
--   warm:
--       2 прогревающих запуска;
--       10 измеряемых запусков без очистки кэша.
--
-- Основной показатель:
--       медиана Execution Time.
--
-- Процедура измерения:
--
--     benchmark/benchmark_runner.sql
--
-- Медианы warm-cache, полученные в эксперименте:
--
--     Model I:     25 275.591 ms
--     Model II:    23 371.178 ms
--     Model III:        0.487 ms
--     Model IV:        12.408 ms
--
-- Значения III и IV нельзя интерпретировать как полное
-- ускорение всей процедуры обработки относительно I и II,
-- поскольку пространственная обработка для этих моделей
-- была перенесена на этап предварительного формирования
-- аналитических структур.
-- ============================================================
