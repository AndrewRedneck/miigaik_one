-- ============================================================
-- З-2. Анализ динамики посевных площадей
-- ============================================================
-- Назначение:
-- определение площади посевов сельскохозяйственных культур
-- по сезонам за период 2024–2026 гг.
--
-- Измерения:
--   время;
--   культура.
--
-- Показатель:
--   площадь посева, га.
--
-- Период экспериментального запроса:
--   2024–2026 гг.
--
-- Для моделей I и II площадь рассчитывается непосредственно
-- по исходной геометрии.
--
-- Для моделей III и IV используются предварительно
-- сформированные аналитические структуры.
-- ============================================================


-- ============================================================
-- MODEL I
-- Базовая реляционная модель
-- ============================================================

SELECT
    season,
    crop,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v1_sowing_relational

WHERE season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL

GROUP BY
    season,
    crop;


-- ============================================================
-- MODEL II
-- Реляционная модель с индексированием
-- ============================================================

SELECT
    season,
    crop,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v2_sowing_indexed

WHERE season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL

GROUP BY
    season,
    crop;


-- ============================================================
-- MODEL III
-- Материализованные представления
-- ============================================================

SELECT
    season,
    crop,
    area_ha

FROM public.mv_crop_season

WHERE season BETWEEN 2024 AND 2026;


-- ============================================================
-- MODEL IV
-- Многомерная модель типа «звезда»
-- ============================================================

SELECT
    dt.season,
    dc.crop_code AS crop,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_time AS dt
  ON dt.time_id = f.time_id

JOIN olap.dim_crop AS dc
  ON dc.crop_id = f.crop_id

WHERE dt.season BETWEEN 2024 AND 2026

GROUP BY
    dt.season,
    dc.crop_code;


-- ============================================================
-- Проверка семантической эквивалентности
-- ============================================================
--
-- До проведения измерений результаты З-2 были сопоставлены
-- для всех четырех архитектур.
--
-- Сравнение выполнялось для каждой комбинации:
--
--     season × crop
--
-- за сезоны 2024, 2025 и 2026 гг.
--
-- Количественно значимых расхождений между моделями
-- обнаружено не было. Наблюдавшиеся различия площади
-- находились на уровне погрешности арифметики
-- double precision и были обусловлены различным порядком
-- суммирования исходных значений.
