--
-- Небольшое различие последних десятичных разрядов
-- обусловлено порядком суммирования double precision.
-- ============================================================


-- ============================================================
-- 8. Интерпретация З-8
-- ============================================================
--
-- MODEL I / MODEL II
-- ------------------------------------------------------------
-- Измеряемая операция непосредственно включает:
--
--     ST_Transform(geom, 3857)
--     ST_Area(...)
--     SUM(...)
--
-- то есть площадь вычисляется из исходной геометрии
-- во время выполнения аналитического запроса.
--
--
-- MODEL III / MODEL IV
-- ------------------------------------------------------------
-- Площадь была рассчитана при предварительном формировании
-- производных структур.
--
-- Аналитический запрос выполняет только:
--
--     фильтрацию;
--     чтение area_ha;
--     суммирование готовых значений.
--
-- Следовательно, MODEL III и MODEL IV не выполняют
-- пространственную операцию расчета площади, эквивалентную
-- MODEL I и MODEL II.
-- ============================================================


-- ============================================================
-- 9. Измерение производительности
-- ============================================================
--
-- Медианы warm-cache:
--
--     Model I:     61.651 ms
--     Model II:    61.708 ms
--     Model III:    0.0325 ms
--     Model IV:     0.230 ms
--
-- Эти значения характеризуют время соответствующей стадии
-- обработки в каждой архитектуре.
--
-- Коэффициенты прямого ускорения MODEL III / MODEL IV
-- относительно MODEL I / MODEL II для З-8 не рассчитываются.
--
-- Причина:
--
--   I / II:
--       непосредственный расчет площади по геометрии;
--
--   III / IV:
--       чтение и суммирование площади, рассчитанной ранее.
--
-- Стоимость предварительного вычисления area_ha для моделей
-- III и IV относится к этапу формирования производных
-- структур и учитывается отдельно.
-- ============================================================


