-- ============================================================
-- З-8. Расчет площади пространственных объектов
-- ============================================================
-- Назначение:
-- оценка выполнения операции расчета площади выбранного
-- фиксированного набора пространственных объектов.
--
-- ВАЖНО:
--
-- реализации З-8 относятся к различным классам обработки.
--
-- MODEL I и MODEL II:
--   площадь рассчитывается непосредственно из исходной
--   геометрии средствами PostGIS.
--
-- MODEL III и MODEL IV:
--   исходная геометрия в производных аналитических
--   структурах отсутствует. Используется площадь,
--   рассчитанная ранее на этапе предварительной обработки.
--
-- Поэтому время выполнения I/II и III/IV не является
-- временем выполнения одной и той же пространственной
-- операции.
-- ============================================================


-- ============================================================
-- 1. Фиксированный набор объектов З-8
-- ============================================================
--
-- Для обеспечения воспроизводимости набор объектов
-- фиксируется отдельно по паре:
--
--     id × season
--
-- Использование season обязательно, поскольку значения id
-- могут повторяться между сезонами.
--
-- В эксперименте использовалось:
--
--     1 555 объектов;
--     season = 2024;
--     территория =
--         'Кавказский муниципальный район'.
--
-- Таблица benchmark_z8_fields содержит только идентификаторы
-- объектов и не дублирует их геометрию.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.benchmark_z8_fields
(
    id     integer NOT NULL,
    season integer NOT NULL,

    PRIMARY KEY (id, season)
);


-- ============================================================
-- 2. MODEL I
-- Непосредственный расчет площади по геометрии
-- ============================================================

SELECT
    COUNT(*) AS field_count,

    SUM(
        ST_Area(
            ST_Transform(f.geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v1_sowing_relational AS f

JOIN public.benchmark_z8_fields AS b
  ON b.id = f.id
 AND b.season = f.season

WHERE f.geom IS NOT NULL;


-- ============================================================
-- 3. MODEL II
-- Непосредственный расчет площади по геометрии
-- ============================================================

SELECT
    COUNT(*) AS field_count,

    SUM(
        ST_Area(
            ST_Transform(f.geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v2_sowing_indexed AS f

JOIN public.benchmark_z8_fields AS b
  ON b.id = f.id
 AND b.season = f.season

WHERE f.geom IS NOT NULL;


-- ============================================================
-- 4. MODEL III
-- Получение предварительно рассчитанной площади
-- ============================================================
--
-- MODEL III не хранит геометрию в материализованном
-- представлении.
--
-- Поэтому здесь выполняется получение агрегированной площади
-- для того же набора объектов, территориальная принадлежность
-- которых была определена ранее.
-- ============================================================

SELECT
    SUM(field_count) AS field_count,
    SUM(area_ha) AS area_ha

FROM public.mv_municipality_crop_season

WHERE season = 2024
  AND municipality = 'Кавказский муниципальный район';


-- ============================================================
-- 5. MODEL IV
-- Получение предварительно рассчитанной площади
-- ============================================================

SELECT
    SUM(f.field_count) AS field_count,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_time AS dt
  ON dt.time_id = f.time_id

JOIN olap.dim_municipality AS dm
  ON dm.municipality_id = f.municipality_id

WHERE dt.season = 2024
  AND dm.municipality_name =
      'Кавказский муниципальный район';


-- ============================================================
-- 6. Контроль фиксированного набора
-- ============================================================

SELECT
    COUNT(*) AS benchmark_field_count

FROM public.benchmark_z8_fields;


-- Ожидаемый результат:
--
--     benchmark_field_count = 1 555


