-- ============================================================
-- З-6. Распределение посевных площадей
--      по землепользователям
-- ============================================================
-- Назначение:
-- определение количества объектов и площади посевов
-- в разрезе:
--
--     землепользователь × культура × сезон
--
-- Измерения:
--   землепользователь;
--   культура;
--   время.
--
-- Показатели:
--   количество объектов;
--   площадь, га.
--
-- Период:
--   2024–2026 гг.
--
-- В качестве идентификатора землепользователя используется
-- атрибут land_inn.
--
-- NULL и пустые значения land_inn объединяются
-- в категорию:
--
--     'Не определено'
--
-- Для моделей I и II агрегация выполняется непосредственно
-- по исходным данным.
--
-- Для модели III используется специализированное
-- материализованное представление.
--
-- Для модели IV используется отдельное измерение
-- землепользователей dim_land_user.
-- ============================================================


-- ============================================================
-- MODEL I
-- Базовая реляционная модель
-- ============================================================

SELECT
    COALESCE(
        NULLIF(land_inn, ''),
        'Не определено'
    ) AS land_inn,

    crop,
    season,

    COUNT(*) AS field_count,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v1_sowing_relational

WHERE season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL

GROUP BY
    COALESCE(
        NULLIF(land_inn, ''),
        'Не определено'
    ),
    crop,
    season;


-- ============================================================
-- MODEL II
-- Реляционная модель с индексированием
-- ============================================================

SELECT
    COALESCE(
        NULLIF(land_inn, ''),
        'Не определено'
    ) AS land_inn,

    crop,
    season,

    COUNT(*) AS field_count,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v2_sowing_indexed

WHERE season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL

GROUP BY
    COALESCE(
        NULLIF(land_inn, ''),
        'Не определено'
    ),
    crop,
    season;


-- ============================================================
-- MODEL III
-- Материализованные представления
-- ============================================================

SELECT
    land_inn,
    crop,
    season,
    field_count,
    area_ha

FROM public.mv_land_user_crop_season

WHERE season BETWEEN 2024 AND 2026;


-- ============================================================
-- MODEL IV
-- Многомерная модель типа «звезда»
-- ============================================================

SELECT
    dl.land_inn,
    dc.crop_code AS crop,
    dt.season,

    SUM(f.field_count) AS field_count,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_time AS dt
  ON dt.time_id = f.time_id

JOIN olap.dim_crop AS dc
  ON dc.crop_id = f.crop_id

JOIN olap.dim_land_user AS dl
  ON dl.land_user_id = f.land_user_id

WHERE dt.season BETWEEN 2024 AND 2026

GROUP BY
    dl.land_inn,
    dc.crop_code,
    dt.season;


-- ============================================================
-- Проверка семантической эквивалентности
-- ============================================================
--
-- Результаты четырех реализаций З-6 были сопоставлены
-- по комбинации:
--
--     land_inn × crop × season
--
-- Перед проведением измерений было подтверждено:
--
--   - совпадение состава групп;
--   - совпадение field_count;
--   - совпадение площади с учетом погрешности
--     вычислений double precision.
--
-- Для всех моделей применяется одинаковая обработка
-- отсутствующего идентификатора землепользователя:
--
--     COALESCE(NULLIF(land_inn, ''), 'Не определено')
--
-- Это исключает различия результатов, вызванные отдельной
-- обработкой NULL и пустых строк.
-- ============================================================


-- ============================================================
-- Особенности архитектур
-- ============================================================
--
-- MODEL I
--   выполняет расчет площади каждого исходного объекта
--   и последующую группировку по:
--
--       land_inn × crop × season.
--
-- MODEL II
--   выполняет ту же операцию над исходными объектами.
--   Индекс по land_inn специально не создавался, поскольку
--   он не входил в исследуемую конфигурацию модели II.
--
-- MODEL III
--   использует материализованное представление
--
--       mv_land_user_crop_season
--
--   имеющее ту же гранулярность, что и результат З-6:
--
--       season × crop × land_inn.
--
-- MODEL IV
--   использует таблицу фактов с гранулярностью:
--
--       season × crop × municipality × land_user.
--
--   Поэтому для получения результата З-6 показатели
--   суммируются по муниципальным образованиям.
--
-- Наличие dim_land_user является обязательным условием
-- семантической эквивалентности модели IV остальным
-- архитектурам для данного аналитического сценария.
-- ============================================================


