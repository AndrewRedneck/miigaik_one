-- ============================================================
-- З-5. Определение 10 культур с наибольшей
--      суммарной площадью посевов
-- ============================================================
-- Назначение:
-- ранжирование сельскохозяйственных культур по суммарной
-- площади посевов за исследуемый период.
--
-- Измерение:
--   культура.
--
-- Показатель:
--   суммарная площадь посева, га.
--
-- Период:
--   2024–2026 гг.
--
-- Результат:
--   10 культур с наибольшей суммарной площадью.
--
-- Для моделей I и II площадь рассчитывается непосредственно
-- по исходной геометрии.
--
-- Для моделей III и IV используются предварительно
-- сформированные агрегированные показатели.
-- ============================================================


-- ============================================================
-- MODEL I
-- Базовая реляционная модель
-- ============================================================

SELECT
    crop,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v1_sowing_relational

WHERE season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL

GROUP BY crop

ORDER BY area_ha DESC

LIMIT 10;


-- ============================================================
-- MODEL II
-- Реляционная модель с индексированием
-- ============================================================

SELECT
    crop,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v2_sowing_indexed

WHERE season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL

GROUP BY crop

ORDER BY area_ha DESC

LIMIT 10;


-- ============================================================
-- MODEL III
-- Материализованные представления
-- ============================================================

SELECT
    crop,
    SUM(area_ha) AS area_ha

FROM public.mv_crop_season

WHERE season BETWEEN 2024 AND 2026

GROUP BY crop

ORDER BY area_ha DESC

LIMIT 10;


-- ============================================================
-- MODEL IV
-- Многомерная модель типа «звезда»
-- ============================================================

SELECT
    dc.crop_code AS crop,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_time AS dt
  ON dt.time_id = f.time_id

JOIN olap.dim_crop AS dc
  ON dc.crop_id = f.crop_id

WHERE dt.season BETWEEN 2024 AND 2026

GROUP BY dc.crop_code

ORDER BY area_ha DESC

LIMIT 10;


-- ============================================================
-- Проверка семантической эквивалентности
-- ============================================================
--
-- Перед измерением производительности результаты четырех
-- реализаций З-5 были сопоставлены.
--
-- Для всех четырех архитектур был получен одинаковый
-- состав 10 культур с наибольшей суммарной площадью
-- за 2024–2026 гг.
--
-- Порядок культур также совпадал.
--
-- Различия численных значений площади ограничивались
-- погрешностью вычислений double precision, возникающей
-- вследствие различного порядка суммирования.
--
-- Таким образом, сравнение производительности выполнялось
-- для семантически эквивалентных результатов.
-- ============================================================


-- ============================================================
-- Особенности выполнения
-- ============================================================
--
-- MODEL I
--   выполняет фильтрацию исходных записей,
--   расчет площади каждой геометрии,
--   группировку по crop,
--   сортировку и LIMIT 10.
--
-- MODEL II
--   выполняет аналогичные операции, но может использовать
--   индексы модели II в соответствии с выбранным
--   PostgreSQL планом выполнения.
--
-- MODEL III
--   использует mv_crop_season, где площадь уже рассчитана
--   для комбинации season × crop. При выполнении З-5
--   требуется только суммирование трех сезонных агрегатов
--   для каждой культуры, сортировка и LIMIT 10.
--
-- MODEL IV
--   использует таблицу фактов, имеющую более детальную
--   гранулярность:
--
--       season × crop × municipality × land_user
--
--   поэтому площадь дополнительно агрегируется по культуре
--   за все муниципальные образования, землепользователей
--   и сезоны исследуемого периода.
-- ============================================================


