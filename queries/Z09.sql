-- ============================================================
-- З-9. Фильтрация по заданной культуре и периоду
-- ============================================================
-- Назначение:
-- определение количества объектов и суммарной площади
-- посевов заданной сельскохозяйственной культуры
-- за выбранный период.
--
-- Параметры экспериментального запроса:
--
--     crop   = 1010105
--     period = 2024–2026
--
-- Показатели:
--     количество объектов;
--     суммарная площадь, га.
--
-- В отличие от З-7 и З-8 данный сценарий не требует
-- территориального пространственного сопоставления.
--
-- Для моделей I и II площадь рассчитывается непосредственно
-- по исходным геометриям.
--
-- Для моделей III и IV используются предварительно
-- рассчитанные значения площади.
-- ============================================================


-- ============================================================
-- MODEL I
-- Базовая реляционная модель
-- ============================================================

SELECT
    COUNT(*) AS field_count,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v1_sowing_relational

WHERE crop = 1010105
  AND season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL;


-- ============================================================
-- MODEL II
-- Реляционная модель с индексированием
-- ============================================================

SELECT
    COUNT(*) AS field_count,

    SUM(
        ST_Area(
            ST_Transform(geom, 3857)
        )
    ) / 10000.0 AS area_ha

FROM public.v2_sowing_indexed

WHERE crop = 1010105
  AND season BETWEEN 2024 AND 2026
  AND geom IS NOT NULL
  AND crop IS NOT NULL;


-- ============================================================
-- MODEL III
-- Материализованные представления
-- ============================================================

SELECT
    SUM(field_count) AS field_count,
    SUM(area_ha) AS area_ha

FROM public.mv_crop_season

WHERE crop = 1010105
  AND season BETWEEN 2024 AND 2026;


-- ============================================================
-- MODEL IV
-- Многомерная модель типа «звезда»
-- ============================================================

SELECT
    SUM(f.field_count) AS field_count,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_time AS dt
  ON dt.time_id = f.time_id

JOIN olap.dim_crop AS dc
  ON dc.crop_id = f.crop_id

WHERE dc.crop_code = 1010105
  AND dt.season BETWEEN 2024 AND 2026;


-- ============================================================
-- Контроль результата
-- ============================================================
--
-- Для:
--
--     crop = 1010105
--     season = 2024–2026
--
-- всеми четырьмя реализациями получен семантически
-- эквивалентный результат:
--
--     field_count = 89 366
--
--     area_ha ≈ 6 526 664.9496138 га
--
-- Различия последних десятичных разрядов площади между
-- архитектурами обусловлены порядком суммирования значений
-- double precision.
-- ============================================================


-- ============================================================
-- Особенности выполнения
-- ============================================================
--
-- MODEL I
-- ------------------------------------------------------------
-- Фильтрует исходные записи по crop и season, после чего
-- рассчитывает площадь каждой выбранной геометрии.
--
--
-- MODEL II
-- ------------------------------------------------------------
-- Может использовать:
--
--     idx_v2_crop
--     idx_v2_season
--     idx_v2_season_crop
--
-- в зависимости от плана, выбранного PostgreSQL.
--
-- Наличие индекса не задает план принудительно:
-- решение о его использовании принимает оптимизатор.
--
--
-- MODEL III
-- ------------------------------------------------------------
-- Использует mv_crop_season с гранулярностью:
--
--     season × crop
--
-- поэтому для выполнения З-9 требуется выбрать три
-- сезонных агрегата заданной культуры и суммировать
-- field_count и area_ha.
--
--
-- MODEL IV
-- ------------------------------------------------------------
-- Таблица фактов имеет гранулярность:
--
--     season × crop × municipality × land_user
--
-- поэтому после фильтрации по культуре и периоду показатели
-- суммируются по муниципальным образованиям и
-- землепользователям.
-- ============================================================


-- ============================================================
-- Семантическая эквивалентность
-- ============================================================
--
-- Перед измерением производительности было проверено:
--
--     field_count:
--         совпадает для моделей I–IV;
--
--     area_ha:
--         совпадает с учетом погрешности double precision.
--
-- Таким образом, в З-9 четыре архитектуры возвращают
-- одинаковый аналитический показатель при одинаковых
-- параметрах фильтрации.
--
-- В отличие от З-7 и З-8 З-9 не выделяется в отдельный
-- класс пространственных операций.
--
-- При этом при интерпретации времени моделей III и IV
-- необходимо учитывать, что расчет area_ha был перенесен
-- на этап предварительного формирования структур.
-- ============================================================


