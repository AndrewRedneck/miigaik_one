-- ============================================================
-- З-7. Определение объектов в пределах выбранного
--      муниципального образования
-- ============================================================
-- Назначение:
-- определение количества объектов и их суммарной площади
-- для заданного муниципального образования и сезона.
--
-- Параметры экспериментального запроса:
--
--   season       = 2024
--   municipality = 'Кавказский муниципальный район'
--
-- Показатели:
--   количество объектов;
--   суммарная площадь, га.
--
-- ВАЖНО:
--
-- реализации З-7 относятся к двум различным классам
-- обработки.
--
-- MODEL I и MODEL II:
--   пространственная принадлежность объектов определяется
--   непосредственно при выполнении запроса.
--
-- MODEL III и MODEL IV:
--   используется результат территориального отнесения,
--   рассчитанный ранее при формировании производных
--   аналитических структур.
--
-- Поэтому время I/II и III/IV не следует интерпретировать
-- как прямое ускорение одной и той же вычислительной
-- операции.
-- ============================================================


-- ============================================================
-- MODEL I
-- Непосредственная пространственная обработка
-- ============================================================

WITH candidates AS
(
    SELECT
        f.id,
        f.season,

        ST_Area(
            ST_Transform(f.geom, 3857)
        ) / 10000.0 AS area_ha,

        m."m.name" AS municipality,

        ST_Area(
            ST_Transform(
                ST_Intersection(f.geom, m.geom),
                3857
            )
        )
        /
        NULLIF(
            ST_Area(
                ST_Transform(f.geom, 3857)
            ),
            0
        ) AS overlap_ratio

    FROM public.v1_sowing_relational AS f

    JOIN public.municipalities AS m
      ON ST_Intersects(f.geom, m.geom)

    WHERE f.season = 2024
      AND f.geom IS NOT NULL
      AND f.crop IS NOT NULL
),

best_match AS
(
    SELECT
        *,

        ROW_NUMBER() OVER
        (
            PARTITION BY season, id
            ORDER BY overlap_ratio DESC
        ) AS rn

    FROM candidates
),

assigned AS
(
    SELECT
        area_ha,

        CASE
            WHEN overlap_ratio > 0.8
                THEN municipality
            ELSE 'Не определено'
        END AS municipality

    FROM best_match

    WHERE rn = 1
)

SELECT
    COUNT(*) AS field_count,
    SUM(area_ha) AS area_ha

FROM assigned

WHERE municipality = 'Кавказский муниципальный район';


-- ============================================================
-- MODEL II
-- Непосредственная пространственная обработка
-- с индексированной исходной таблицей
-- ============================================================

