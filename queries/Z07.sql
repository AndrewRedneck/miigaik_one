SELECT
    COUNT(*) AS field_count,
    SUM(area_ha) AS area_ha

FROM assigned

WHERE municipality = 'Кавказский муниципальный район';


-- ============================================================
-- MODEL III
-- Получение предварительно рассчитанного результата
-- ============================================================

SELECT
    SUM(field_count) AS field_count,
    SUM(area_ha) AS area_ha

FROM public.mv_municipality_crop_season

WHERE season = 2024
  AND municipality = 'Кавказский муниципальный район';


-- ============================================================
-- MODEL IV
-- Получение предварительно рассчитанного результата
-- ============================================================

SELECT
    SUM(f.field_count) AS field_count,
    SUM(f.area_ha) AS area_ha

FROM olap.fact_sowing AS f

JOIN olap.dim_time AS dt
  ON dt.time_id = f.time_id

JOIN olap.dim_municipality AS dm
  ON dm.municipality_id = f.municipality_id

WHERE dt.season = 2024
  AND dm.municipality_name =
      'Кавказский муниципальный район';


-- ============================================================
-- Контроль результата
-- ============================================================
--
-- Для параметров:
--
--   season       = 2024
--   municipality = 'Кавказский муниципальный район'
--
-- получен следующий результат:
--
--     field_count = 1 555
--
--     area_ha ≈ 135 599.414966409
--
-- MODEL I:
--     1 555 объектов
--     135599.41496640924 га
--
-- MODEL II:
--     1 555 объектов
--     результат совпадает с MODEL I с учетом погрешности
--     double precision.
--
-- MODEL III и MODEL IV:
--     тот же field_count и эквивалентная площадь,
--     полученные из предварительно сформированных
--     агрегированных структур.
-- ============================================================


-- ============================================================
-- Интерпретация З-7
-- ============================================================
--
-- MODEL I / MODEL II
-- ------------------------------------------------------------
-- Запрос выполняет непосредственно:
--
--     ST_Intersects;
--     ST_Intersection;
--     ST_Transform;
--     ST_Area;
--     расчет overlap_ratio;
--     выбор максимального пересечения;
--     проверку overlap_ratio > 0.8.
--
-- Следовательно, измеряемое время включает стоимость
-- пространственного определения территориальной
-- принадлежности.
--
--
-- MODEL III / MODEL IV
-- ------------------------------------------------------------
-- Пространственная принадлежность уже была определена
-- при формировании:
--
--     mv_municipality_crop_season
--
-- или:
--
--     olap.fact_sowing.
--
-- З-7 выполняет только фильтрацию и агрегацию
-- предварительно подготовленных данных.
--
-- Поэтому MODEL III и MODEL IV в данном сценарии
-- не выполняют пространственную операцию, эквивалентную
-- операции MODEL I и MODEL II.
-- ============================================================


-- ============================================================
-- Измерение производительности
-- ============================================================
--
-- Медианы warm-cache:
--
--     Model I:     5 171.659 ms
--     Model II:    5 240.938 ms
--     Model III:       0.034 ms
--     Model IV:        0.233 ms
--
-- Эти четыре значения приводятся для характеристики
-- времени соответствующих реализаций З-7.
--
-- Коэффициент прямого ускорения MODEL III или MODEL IV
-- относительно MODEL I / MODEL II для З-7 не рассчитывается,
-- поскольку сравниваются разные стадии обработки:
--
--     I / II   — пространственное вычисление;
--
--     III / IV — чтение предварительно рассчитанного
--                результата.
--
-- Стоимость формирования производных структур III и IV
-- учитывается отдельно в эксперименте предварительной
-- обработки.
-- ============================================================


