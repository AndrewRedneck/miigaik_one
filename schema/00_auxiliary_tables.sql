-- ============================================================
-- Вспомогательные пространственные данные
-- ============================================================
-- Исследование:
-- «Сравнительный анализ архитектур хранения
-- пространственно-временных данных в геоинформационных
-- системах мониторинга посевных площадей»
--
-- Для территориального отнесения пространственных объектов
-- используется отдельный слой муниципальных образований:
--
--     public.municipalities
--
-- Этот слой не является одной из четырех исследуемых
-- архитектур хранения. Он представляет собой вспомогательные
-- пространственные данные, одинаково используемые при
-- выполнении соответствующих операций.
--
-- В экспериментальных SQL-сценариях из данного слоя
-- используются только:
--
--     "m.name" — наименование муниципального образования;
--     geom     — геометрия муниципального образования.
--
-- Полная структура исходного административного слоя
-- для воспроизведения эксперимента не требуется.
-- ============================================================


-- ------------------------------------------------------------
-- 1. Минимальная структура вспомогательного слоя
-- ------------------------------------------------------------
--
-- Следующее определение показывает минимальную структуру,
-- необходимую для выполнения опубликованных SQL-сценариев.
--
-- При использовании собственного административного слоя
-- названия соответствующих столбцов могут быть изменены
-- в запросах.
-- ------------------------------------------------------------

CREATE TABLE public.municipalities
(
    "m.name" varchar,
    geom     geometry
);


-- ============================================================
-- 2. Требования к пространственным данным
-- ============================================================
--
-- Таблица должна содержать полигональные геометрии
-- муниципальных образований исследуемой территории.
--
-- Значение "m.name" используется как идентификатор
-- муниципального образования в аналитических результатах.
--
-- Геометрия используется для:
--
--   - пространственного соединения с объектами посевов;
--   - расчета площади пересечения;
--   - определения доли пространственного объекта,
--     приходящейся на муниципальное образование;
--   - выбора муниципального образования с максимальной
--     долей пересечения.
--
-- Пространственные данные муниципальных образований
-- должны быть приведены к системе координат, совместимой
-- с геометрией исходных объектов посевов для выполнения
-- ST_Intersects и ST_Intersection.
-- ============================================================


-- ============================================================
-- 3. Правило территориального отнесения
-- ============================================================
--
-- Территориальная принадлежность объекта определяется
-- не только фактом пересечения с муниципальным образованием.
--
-- Для каждого исходного объекта:
--
--   1. определяются все муниципальные образования,
--      пересекающие его геометрию;
--
--   2. для каждого пересечения рассчитывается:
--
--      площадь пересечения / площадь исходного объекта;
--
--   3. выбирается муниципальное образование с максимальным
--      значением данного отношения;
--
--   4. объект относится к выбранному муниципальному
--      образованию только при условии:
--
--          overlap_ratio > 0.8
--
--   5. если условие не выполняется, объект относится
--      к категории:
--
--          'Не определено'
--
-- В экспериментальном наборе после исключения записей
-- с отсутствующими geom или crop территориальному
-- сопоставлению подлежало 324 314 объектов.
--
-- Результат применения правила:
--
-- season | определено | не определено
-- -------+-------------+--------------
-- 2024   | 78 709      | 18
-- 2025   | 122 120     | 31
-- 2026   | 123 407     | 29
--
-- Всего объектов категории «Не определено»: 78.
-- ============================================================


-- ============================================================
-- 4. Контроль вспомогательного слоя
-- ============================================================

SELECT
    COUNT(*) AS municipality_count
FROM public.municipalities;


-- Контроль отсутствующих геометрий.

SELECT
    COUNT(*) AS null_geometry_count
FROM public.municipalities
WHERE geom IS NULL;


-- Контроль отсутствующих наименований.

SELECT
    COUNT(*) AS null_name_count
FROM public.municipalities
WHERE "m.name" IS NULL;


-- ============================================================
-- 5. Проверка пространственного пересечения
-- ============================================================
--
-- Следующий запрос позволяет проверить, что валидные
-- исходные объекты имеют хотя бы одно пересечение
-- с муниципальным слоем.
--
-- В качестве исходной таблицы здесь используется модель I.
-- ============================================================

SELECT
    COUNT(*) AS fields_without_intersection

FROM public.v1_sowing_relational AS f

WHERE f.geom IS NOT NULL
  AND f.crop IS NOT NULL

  AND NOT EXISTS
  (
      SELECT 1
      FROM public.municipalities AS m
      WHERE ST_Intersects(f.geom, m.geom)
  );


