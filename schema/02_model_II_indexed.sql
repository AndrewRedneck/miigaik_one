-- ============================================================
-- Модель II. Реляционная модель с индексированием
-- ============================================================
-- Исследование:
-- «Сравнительный анализ архитектур хранения
-- пространственно-временных данных в геоинформационных
-- системах мониторинга посевных площадей»
--
-- Модель II сохраняет исходные пространственно-временные
-- данные на уровне отдельных объектов, аналогично модели I,
-- но дополняется пространственным и атрибутивными индексами.
--
-- В эксперименте использовались:
--   1. GiST-индекс по геометрии;
--   2. B-tree индекс по сезону;
--   3. B-tree индекс по культуре;
--   4. составной B-tree индекс по сезону и культуре.
-- ============================================================


-- ------------------------------------------------------------
-- 1. Исходная таблица
-- ------------------------------------------------------------

CREATE TABLE public.v2_sowing_indexed
(
    id          integer,
    geom        geometry,
    id_sub      varchar,
    rgis_code   varchar,
    onfarm_cod  varchar,
    season      integer,
    crop        integer,
    okpd2       varchar,
    crop_vid    varchar,
    comment     varchar,
    land_inn    varchar,
    land_kpp    varchar,
    date_sow    date,
    batch_num   varchar,
    crop_num    varchar,
    seeds_val   varchar,
    purpose     integer,
    gos_crop    integer,
    plan_use    integer,
    d_sow_end   date,
    products    integer
);


-- ------------------------------------------------------------
-- 2. Пространственный индекс
-- ------------------------------------------------------------

CREATE INDEX idx_v2_geom_gist
    ON public.v2_sowing_indexed
    USING gist (geom);


-- ------------------------------------------------------------
-- 3. Атрибутивные индексы
-- ------------------------------------------------------------

CREATE INDEX idx_v2_season
    ON public.v2_sowing_indexed (season);

CREATE INDEX idx_v2_crop
    ON public.v2_sowing_indexed (crop);

CREATE INDEX idx_v2_season_crop
    ON public.v2_sowing_indexed (season, crop);


-- ------------------------------------------------------------
-- 4. Формирование статистики оптимизатора
-- ------------------------------------------------------------

ANALYZE public.v2_sowing_indexed;


-- ------------------------------------------------------------
-- 5. Контроль количества записей
-- ------------------------------------------------------------
-- Для экспериментального набора данных:
-- всего 330 721 запись.

SELECT COUNT(*) AS source_row_count
FROM public.v2_sowing_indexed;


-- ------------------------------------------------------------
-- 6. Контроль распределения по сезонам
-- ------------------------------------------------------------
-- В исходном эксперименте:
-- 2024:  78 748 записей
-- 2025: 127 302 записи
-- 2026: 124 671 запись

SELECT
    season,
    COUNT(*) AS row_count
FROM public.v2_sowing_indexed
GROUP BY season
ORDER BY season;


-- ------------------------------------------------------------
-- 7. Контроль записей с геометрией и кодом культуры
-- ------------------------------------------------------------

SELECT
    season,
    COUNT(*) AS valid_row_count
FROM public.v2_sowing_indexed
WHERE geom IS NOT NULL
  AND crop IS NOT NULL
GROUP BY season
ORDER BY season;


-- ------------------------------------------------------------
-- 8. Контроль созданных индексов
-- ------------------------------------------------------------

SELECT
    indexname,
    indexdef
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename = 'v2_sowing_indexed'
ORDER BY indexname;


