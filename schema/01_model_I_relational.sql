-- ============================================================
-- Модель I. Базовая реляционная модель
-- ============================================================
-- Исследование:
-- «Сравнительный анализ архитектур хранения
-- пространственно-временных данных в геоинформационных
-- системах мониторинга посевных площадей»
--
-- Модель I используется в качестве базового варианта
-- организации данных.
--
-- Все исходные пространственно-временные данные хранятся
-- в одной таблице. Дополнительные пользовательские индексы
-- и предварительно агрегированные структуры не создаются.
-- ============================================================


-- ------------------------------------------------------------
-- 1. Исходная таблица
-- ------------------------------------------------------------

CREATE TABLE public.v1_sowing_relational
(
    id          integer,
    geom        geometry,
    id_sub      varchar,
    rgis_code   varchar,
    onfarm_cod  varchar,
    season      integer,
    crop        integer,
    okpd2       varchar,
    crop_vid    varchar,
    comment     varchar,
    land_inn    varchar,
    land_kpp    varchar,
    date_sow    date,
    batch_num   varchar,
    crop_num    varchar,
    seeds_val   varchar,
    purpose     integer,
    gos_crop    integer,
    plan_use    integer,
    d_sow_end   date,
    products    integer
);


-- ------------------------------------------------------------
-- 2. Статистика оптимизатора
-- ------------------------------------------------------------
-- После загрузки исходного набора данных выполняется ANALYZE
-- для формирования статистики, используемой планировщиком
-- PostgreSQL.

ANALYZE public.v1_sowing_relational;


-- ------------------------------------------------------------
-- 3. Контроль количества записей
-- ------------------------------------------------------------
-- Для набора данных, использованного в эксперименте,
-- исходная таблица содержала 330 721 запись.

SELECT COUNT(*) AS source_row_count
FROM public.v1_sowing_relational;


-- ------------------------------------------------------------
-- 4. Контроль распределения по сезонам
-- ------------------------------------------------------------
-- В исходном эксперименте:
-- 2024:  78 748 записей
-- 2025: 127 302 записи
-- 2026: 124 671 запись

SELECT
    season,
    COUNT(*) AS row_count
FROM public.v1_sowing_relational
GROUP BY season
ORDER BY season;


-- ------------------------------------------------------------
-- 5. Контроль записей, пригодных для формирования
--    производных аналитических структур
-- ------------------------------------------------------------
-- При построении производных структур моделей III и IV
-- использовались записи, для которых одновременно заданы
-- геометрия и код сельскохозяйственной культуры.
--
-- В экспериментальном наборе:
-- 2024:  78 727 записей
-- 2025: 122 151 запись
-- 2026: 123 436 записей
-- Всего: 324 314 записей.

SELECT
    season,
    COUNT(*) AS valid_row_count
FROM public.v1_sowing_relational
WHERE geom IS NOT NULL
  AND crop IS NOT NULL
GROUP BY season
ORDER BY season;


-- ------------------------------------------------------------
-- 6. Контроль отсутствия дополнительных пользовательских
--    индексов
-- ------------------------------------------------------------
-- Для модели I дополнительные индексы в рамках эксперимента
-- не создавались.

SELECT
    indexname,
    indexdef
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename = 'v1_sowing_relational'
ORDER BY indexname;
